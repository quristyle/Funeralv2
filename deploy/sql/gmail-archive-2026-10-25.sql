-- Gmail 보관함 — scom.gmail_accounts · scom.gmail_messages (2026-10-25)
-- ============================================================
--
-- 서버: microservices/AIAgentServer/Services/Gmail/
--
-- **EF 마이그레이션이 아니다.** RAG·사용량·업무 비서 기록 표와 같은 자리다.
--
--   psql -h … -U funeralv2 -d jsiniportal -f gmail-archive-2026-10-25.sql
--
-- 두 번 돌려도 안전하다.
--
-- ── 받는 길이 셋인데 표는 하나다 ────────────────────────────
--
-- 같은 메일이 길 셋으로 들어온다. Takeout(mbox)이 과거를 한꺼번에 붓고,
-- 그 뒤로는 Workspace 계정은 Gmail API 가, 개인 계정은 IMAP 이 증분을 받는다.
-- 셋이 겹치는 구간이 반드시 생기므로(Takeout 을 내보낸 시점과 증분이 시작된
-- 시점 사이) **겹침을 지우는 열쇠가 필요하다.**
--
-- 그 열쇠는 `rfc822_message_id` 다 — 메일 헤더의 `Message-ID` 로, 보낸 서버가
-- 붙이고 길이 달라져도 안 바뀐다. 반대로 Gmail 의 메시지 id 와 IMAP 의 UID 는
-- **길마다 다른 값**이라 겹침을 못 가른다(같은 메일인데 서로 다른 번호다).
-- 그래서 고유 색인은 (account_id, rfc822_message_id) 에 건다.
--
-- 드물게 Message-ID 가 없는 메일이 있다(직접 만든 메일 · 아주 옛 메일).
-- 그때는 NULL 이 들어가고 고유 색인이 안 걸리므로, 적재하는 쪽이
-- 길+제공자 id 로 한 번 더 본다 — ux_gmail_messages_provider 가 그 자리다.
--
-- ── 본문을 통째로 담는다 ────────────────────────────────────
--
-- 비서가 도구로 물을 때 본문이 있어야 답이 된다. 전체 과거를 받으면 수 GB 가
-- 될 수 있는데, 그래도 자르지 않는다 — 자른 본문으로는 「작년에 계약 관련해서
-- 뭐라고 했더라」에 답할 수 없다. 대신 **오래된 것은 RAG 로 옮기고 나면
-- body_html 을 비울 수 있다**(rag_doc_id 가 찬 줄). 글자 본문만 남긴다.
--
-- ── 사생활 ──────────────────────────────────────────────────
--
-- 지금은 본인 두 계정만 받는다. 그래도 업무 비서는 슈퍼관리자·임원이 함께
-- 쓰는 화면이라, 도구를 그대로 열면 **다른 임원이 이 사람의 개인 메일을
-- 읽을 수 있다.** search_gmail 은 account_id 를 묻는 사람 것으로 좁혀야 한다
-- (docs/gmail-archive.md 「누가 누구 메일을 보는가」).
-- ============================================================

-- ── 받아 오는 계정 ───────────────────────────────────────────
CREATE TABLE IF NOT EXISTS scom.gmail_accounts (
    id              text         NOT NULL,   -- 'imrbiz' · 'personal' 처럼 사람이 읽는 짧은 열쇠
    email           text         NOT NULL,
    owner_login_id  text         NOT NULL,   -- 포털 로그인 아이디. 도구가 이것으로 범위를 좁힌다
    kind            text         NOT NULL,   -- 'api'(Gmail API) · 'imap'
    enabled         boolean      NOT NULL DEFAULT true,

    -- 증분 이어받기 표식. 길에 따라 쓰는 칸이 다르다.
    last_history_id text,                    -- Gmail API: users.history.list 의 startHistoryId
    last_uid        bigint,                  -- IMAP: 마지막으로 받은 UID
    uid_validity    bigint,                  -- IMAP: 이 값이 바뀌면 UID 가 통째로 무효다 — 전체를 다시 받아야 한다

    last_sync_at    timestamptz,
    last_error      text,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_gmail_accounts PRIMARY KEY (id),
    CONSTRAINT ck_gmail_accounts_kind CHECK (kind IN ('api', 'imap'))
);

COMMENT ON TABLE  scom.gmail_accounts              IS '메일을 받아 오는 계정과 증분 이어받기 표식';
COMMENT ON COLUMN scom.gmail_accounts.owner_login_id IS '이 메일함의 주인. 업무 비서가 남의 메일을 못 보게 좁히는 열쇠다';
COMMENT ON COLUMN scom.gmail_accounts.uid_validity IS 'IMAP 서버가 이 값을 바꾸면 last_uid 는 쓸 수 없다 — 전체 재수집 신호';

-- ── 메일 한 통 ───────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS scom.gmail_messages (
    id                  bigint       GENERATED BY DEFAULT AS IDENTITY,
    account_id          text         NOT NULL,
    source              text         NOT NULL,   -- 'takeout' · 'api' · 'imap' (어느 길로 들어왔나)
    provider_msg_id     text,                    -- Gmail 메시지 id 또는 IMAP UID. 길 안에서만 고유하다
    thread_id           text,
    rfc822_message_id   text,                    -- 헤더의 Message-ID. 길이 달라도 같은 값 — 겹침을 가르는 열쇠

    subject             text,
    from_addr           text,
    from_name           text,
    to_addrs            jsonb        NOT NULL DEFAULT '[]'::jsonb,
    cc_addrs            jsonb        NOT NULL DEFAULT '[]'::jsonb,
    sent_at             timestamptz,             -- 헤더의 Date. UTC 로 맞춰 넣는다(docs/utc-time.md)

    labels              jsonb        NOT NULL DEFAULT '[]'::jsonb,
    snippet             text,
    body_text           text,
    body_html           text,
    has_attachments     boolean      NOT NULL DEFAULT false,
    attachments         jsonb        NOT NULL DEFAULT '[]'::jsonb,  -- 이름·형식·크기. 실물은 안 받는다

    rag_doc_id          bigint,                  -- RAG 로 옮긴 뒤 그 문서 번호. 차 있으면 본문을 비워도 된다
    created_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_gmail_messages PRIMARY KEY (id),
    CONSTRAINT ck_gmail_messages_source CHECK (source IN ('takeout', 'api', 'imap'))
);

COMMENT ON TABLE  scom.gmail_messages                   IS 'Gmail 에서 받아 온 메일. 길 셋(takeout·api·imap)이 같은 표에 쌓인다';
COMMENT ON COLUMN scom.gmail_messages.rfc822_message_id IS '헤더 Message-ID. 길이 달라도 안 바뀌어 겹침을 가른다. 없는 메일이 드물게 있다';
COMMENT ON COLUMN scom.gmail_messages.provider_msg_id   IS 'Gmail 메시지 id 또는 IMAP UID. 길 안에서만 고유 — 겹침 판정에 쓰면 안 된다';
COMMENT ON COLUMN scom.gmail_messages.attachments       IS '첨부의 이름·형식·크기만. 실물 바이트는 받지 않는다';
COMMENT ON COLUMN scom.gmail_messages.rag_doc_id        IS 'RAG 문서함으로 옮긴 뒤의 문서 번호. 찬 줄은 body_html 을 비워 자리를 아낄 수 있다';

-- 겹침 막이 — 같은 계정에 같은 Message-ID 는 한 번만. NULL 은 색인이 안 걸린다.
CREATE UNIQUE INDEX IF NOT EXISTS ux_gmail_messages_rfc822
    ON scom.gmail_messages (account_id, rfc822_message_id)
    WHERE rfc822_message_id IS NOT NULL;

-- Message-ID 가 없는 메일의 마지막 막이. 길이 다르면 같은 메일이라도 못 거른다.
CREATE UNIQUE INDEX IF NOT EXISTS ux_gmail_messages_provider
    ON scom.gmail_messages (account_id, source, provider_msg_id)
    WHERE provider_msg_id IS NOT NULL;

-- 도구가 거의 늘 「이 계정의 최근 것부터」로 묻는다.
CREATE INDEX IF NOT EXISTS ix_gmail_messages_account_sent
    ON scom.gmail_messages (account_id, sent_at DESC);

-- 보낸 사람으로 좁히는 질문이 잦다(「누구한테서 온 메일」).
CREATE INDEX IF NOT EXISTS ix_gmail_messages_from
    ON scom.gmail_messages (from_addr);

-- RAG 로 아직 안 옮긴 오래된 것을 고르는 배치용.
CREATE INDEX IF NOT EXISTS ix_gmail_messages_pending_rag
    ON scom.gmail_messages (sent_at)
    WHERE rag_doc_id IS NULL;

