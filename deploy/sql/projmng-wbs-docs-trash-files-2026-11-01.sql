-- WBS 개발자 정보(/projmng/wbs/docs) — 원본(Docs.vue)에 있던 것 셋을 받침한다.
--
--   1. 처음 쓴 때·사람(created_*) — 머리줄의 「작성 / 수정」.
--   2. 휴지통(deleted_*) — 지우기는 숨기기고, 되돌릴 수 없는 삭제는 휴지통에서 한 번 더 묻는다.
--   3. 붙인 문서(wbs_doc_files) — 쪽에 HTML 문서를 여러 장 올리거나 주소를 걸어 iframe 으로 보인다.
--
-- 붙인 HTML 은 디스크가 아니라 이 표(html)에 담는다. ProjMngServer 컨테이너에는 데이터 볼륨이 없어
-- 디스크에 두면 배포 때마다 사라진다.
--
-- created_at 은 기본값 없이 더한 뒤 기본값을 건다. 기본값과 함께 더하면 이미 있는 쪽이 전부 「지금」으로
-- 채워져 처음 쓴 때가 둔갑한다 — 모르는 것은 null 로 두고 화면이 「작성 —」으로 보인다.
--
--   psql -h jin114.co.kr -p 31015 -U projmng -d projmng -v ON_ERROR_STOP=1 -f 이파일

BEGIN;

ALTER TABLE projmng.wbs_docs ADD COLUMN IF NOT EXISTS created_at timestamptz;
ALTER TABLE projmng.wbs_docs ADD COLUMN IF NOT EXISTS created_by varchar(100);
ALTER TABLE projmng.wbs_docs ALTER COLUMN created_at SET DEFAULT now();

ALTER TABLE projmng.wbs_docs ADD COLUMN IF NOT EXISTS deleted_at timestamptz;
ALTER TABLE projmng.wbs_docs ADD COLUMN IF NOT EXISTS deleted_by varchar(100);

COMMENT ON COLUMN projmng.wbs_docs.created_at IS '처음 쓴 때. 이 칸을 넣기 전에 만든 쪽은 null';
COMMENT ON COLUMN projmng.wbs_docs.deleted_at IS '휴지통으로 보낸 때. null 이면 살아 있는 쪽';

CREATE TABLE IF NOT EXISTS projmng.wbs_doc_files (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_id      integer      NOT NULL REFERENCES projmng.wbs_docs(id) ON DELETE CASCADE,
    name        varchar(200) NOT NULL,
    url         varchar(2000),
    html        text,
    bytes       bigint       NOT NULL DEFAULT 0,
    sort_order  integer      NOT NULL DEFAULT 100,
    uploaded_at timestamptz  NOT NULL DEFAULT now(),
    uploaded_by varchar(100),
    CONSTRAINT ck_wbs_doc_files_body CHECK ((url IS NULL) <> (html IS NULL))
);

CREATE INDEX IF NOT EXISTS ix_wbs_doc_files_doc ON projmng.wbs_doc_files (doc_id, sort_order, id);

COMMENT ON TABLE  projmng.wbs_doc_files      IS 'WBS 개발자 정보 쪽에 붙인 문서 — 올린 HTML(html) 또는 걸어 둔 주소(url) 중 하나';
COMMENT ON COLUMN projmng.wbs_doc_files.name IS '탭에 적는 이름 — 올릴 때의 파일 이름 또는 주소에 붙인 이름';

COMMIT;
