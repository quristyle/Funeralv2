-- 업무 비서는 묻는 사람의 평소 권한 밖 자료도 본다 — 임원이라면 다른 회사·
-- 다른 사람의 요청글·일정·할 일까지 물어볼 수 있다. 그 선을 넘은 유일한
-- 증거가 이 표다. 그래서 질문이나 도구 인자가 아니라 **답(answer) 을
-- 자르지 않고 그대로** 적는다 — 실제로 무엇이 밖으로 나갔는지가 기록의
-- 전부이지, 무엇을 물었는지나 어떤 도구를 불렀는지는 참고 자료일 뿐이다.
--
-- tool_calls · sources 는 jsonb 배열 글이다(모델이 부른 도구와 그 근거).
-- 찾아보는 화면은 한 사람의 이력을 최신순으로 보일 것이라 (asked_by,
-- asked_at desc) 색인을 둔다.
-- ============================================================

CREATE TABLE IF NOT EXISTS scom.ai_assistant_audit (
    id              bigint       GENERATED BY DEFAULT AS IDENTITY,
    asked_by        text         NOT NULL,
    asked_at        timestamptz  NOT NULL DEFAULT now(),
    question        text         NOT NULL,
    scope_category  text,
    tool_calls      jsonb        NOT NULL DEFAULT '[]'::jsonb,
    sources         jsonb        NOT NULL DEFAULT '[]'::jsonb,
    answer          text         NOT NULL,
    elapsed_ms      bigint       NOT NULL DEFAULT 0,
    error           text,
    CONSTRAINT pk_ai_assistant_audit PRIMARY KEY (id)
);

COMMENT ON TABLE  scom.ai_assistant_audit                IS '업무 비서가 권한 밖 자료를 넘겨다본 흔적. 쌓기만 하고 고치지 않는다';
COMMENT ON COLUMN scom.ai_assistant_audit.asked_by       IS '물은 사람의 로그인 아이디';
COMMENT ON COLUMN scom.ai_assistant_audit.scope_category IS '사내 문서 검색 범위로 고른 RAG 카테고리. 안 골랐으면 null';
COMMENT ON COLUMN scom.ai_assistant_audit.tool_calls     IS '모델이 부른 도구와 인자(JSON 배열)';
COMMENT ON COLUMN scom.ai_assistant_audit.sources        IS '답의 근거로 삼은 자료(JSON 배열)';
COMMENT ON COLUMN scom.ai_assistant_audit.answer         IS '실제로 나간 답 전문. 요약하거나 자르지 않는다 — 이것이 감사의 대상이다';

CREATE INDEX IF NOT EXISTS ix_ai_assistant_audit_asked_by ON scom.ai_assistant_audit (asked_by, asked_at DESC);
