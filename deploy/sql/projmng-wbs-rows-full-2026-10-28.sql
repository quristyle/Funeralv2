-- WBS 상세 목록(/projmng/wbs/rows)을 참고 소스(docs/wbs_참고소스) 기능 그대로 쓰기 위한 칸과 표.
--   · pv_test_case_id  ProjectView 단위테스트 코드 — Activity ID 메뉴의 「단위테스트 상세」 주소
--   · file_group_id    화면설계 문서 첨부(FileServer 그룹)
--   · file_cnt         첨부 건수 — 목록이 줄마다 FileServer 를 묻지 않게 들고 있는다
--   · wbs_task FK      ON UPDATE CASCADE — 「ID 지정」(NOID-… → 확정 ID)이 일감을 데려간다
--   · wbs_work_deleted 지운 줄과 그 일감의 보관본 (원본은 파일로 남겼다)
alter table projmng.wbs_work add column if not exists pv_test_case_id varchar(50);
alter table projmng.wbs_work add column if not exists file_group_id text;
alter table projmng.wbs_work add column if not exists file_cnt integer not null default 0;

alter table projmng.wbs_task drop constraint if exists wbs_task_work_fkey;
alter table projmng.wbs_task add constraint wbs_task_work_fkey
    foreign key (prj_rid, activity_id) references projmng.wbs_work (prj_rid, activity_id)
    on delete cascade on update cascade;

create table if not exists projmng.wbs_work_deleted (
    del_id      bigint generated by default as identity primary key,
    prj_rid     integer     not null,
    activity_id varchar(50) not null,
    row_data    jsonb       not null,
    tasks       jsonb,
    task_cnt    integer     not null default 0,
    deleted_by  text,
    deleted_at  timestamptz not null default now()
);
create index if not exists ix_wbs_work_deleted_prj on projmng.wbs_work_deleted (prj_rid, deleted_at desc);
