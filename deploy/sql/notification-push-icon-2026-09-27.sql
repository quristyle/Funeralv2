-- ============================================================
-- 알림이 띄운 아이콘 — scom.push_send_logs 에 칸 하나
-- ============================================================
--
-- 「내 알림함」이 **앱 알림에 떴던 그 그림**을 목록에 함께 보여 준다. 대개
-- 그 일을 시킨 사람의 프로필 사진이다 — 제목보다 먼저 답하는 물음이
-- 「누가 보낸 것인가」라서, 휴대폰 알림창과 같은 것을 알림함에서도 본다.
--
-- ── 왜 칸이 있어야 하나 — 되짚을 수가 없다 ───────────────────
--
-- 부르는 쪽은 아이콘을 **사람의 아이디**로 지목하고(PushMessageDto.IconOwnerKey)
-- 그것이 발송 직전에 얼굴로 풀린다(PushSender.FillIconAsync). 그런데 그
-- 아이디도, 풀린 주소도 **어디에도 안 남았다.** 알림함은 그 얼굴을 다시
-- 만들 길이 없었다.
--
-- ── sent_by 로 대신할 수 없다 ────────────────────────────────
--
-- 둘은 다른 것을 가리킨다 — 「보낸 주체」와 「누가 시킨 일인가」다.
-- 가장 잦은 AI 작업 알림이 바로 그 경우다:
--
--   category   sent_by         30일 건수
--   ---------  --------------  ---------
--   AI_TASK    AI_TASK               476   ← 사람이 아니다
--   WEATHER    (없음)                 54
--   SIGNUP     AUTH_SIGNUP            26
--
-- 얼굴의 주인은 그 작업을 지시한 사람(projmng.ai_task.cre_id)이다.
--
-- ── 열쇠(?t=)는 떼고 담는다 ──────────────────────────────────
--
-- 알림으로 나가는 주소에는 사진 한 장을 여는 **60분짜리 열쇠**가 붙어 있다
-- (AvatarIconTokenFactory). 로그인해 있지 않은 기기로도 알림이 가기
-- 때문인데, 그대로 담으면 **알림함의 얼굴이 한 시간 뒤에 조용히 그림자로
-- 바뀐다** — 셸의 중계가 그 열쇠를 Bearer 로 올려 보내면서 보는 사람의
-- 신원을 대신하고, 시효가 지난 열쇠는 401 이다. 로그인해서 보고 있어도
-- 그렇다. 떼는 일은 PushSender.IconForLog 가 한다.
--
-- 그러니 이 칸은 「푸시가 쓴 그림」이지 「푸시가 쓴 글자 그대로」는 아니다.
--
-- ── 비어 있는 줄 ─────────────────────────────────────────────
--
-- 사람을 지목하지 않은 알림(날씨 특보·배포 알림)은 NULL 이다. 그때 무엇을
-- 그릴지는 보는 쪽이 정하고, **양쪽이 같아야 한다** —
-- 서비스워커도 알림함도 앱 아이콘(/pwa-icon-192.png)으로 떨어진다.
-- 한쪽만 사람 형상 그림자로 두면 같은 알림이 기기와 알림함에서 다른
-- 그림으로 보인다.
--
-- 옛 줄 채우기는 notification-push-icon-backfill-2026-09-27.sql.
--
-- 멱등하다. 되돌리려면 맨 아래.
-- **운영 반영 완료** (2026-09-27 — 개발과 운영이 같은 DB 를 본다).

BEGIN;

ALTER TABLE scom.push_send_logs
    ADD COLUMN IF NOT EXISTS icon text;

COMMENT ON COLUMN scom.push_send_logs.icon
    IS '이 알림이 띄운 아이콘 주소. 대개 시킨 사람의 프로필 사진(/files/avatar/{파일아이디})이고, 사람을 지목하지 않은 알림은 NULL 이다. 한 시간짜리 열쇠(?t=)는 떼고 담는다 — 붙은 채로 두면 알림함에서 시효가 지난 뒤 그림자로 떨어진다.';

COMMIT;

-- 확인
--   SELECT coalesce(category,'(구분 없음)') AS 구분,
--          count(*) FILTER (WHERE icon IS NOT NULL) AS 얼굴있음,
--          count(*) FILTER (WHERE icon IS NULL)     AS 비어있음,
--          count(*) FILTER (WHERE icon LIKE '%?t=%') AS 열쇠남음
--     FROM scom.push_send_logs GROUP BY 1 ORDER BY 2 DESC;
--
--   열쇠남음 은 언제나 0 이어야 한다. 0 이 아니면 IconForLog 를 안 거친
--   줄이 들어온 것이다.
--
-- 되돌리기
