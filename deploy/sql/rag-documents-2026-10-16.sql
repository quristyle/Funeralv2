--
-- ── 무엇을 담는가 ───────────────────────────────────────────
--
--   카테고리  RAG 한 단위. 색인 파일 하나가 여기에 대응한다.
--     └ 분류  트리. 사람이 문서를 정리하는 서랍이다.
--          └ 파일
--
-- **카테고리를 나누는 까닭**은 섞으면 안 되는 자료가 있기 때문이다. 사내 규정과
-- 제품 설명서를 한 색인에 넣으면 "휴가 며칠인가" 에 제품 문서가 섞여 나온다.
-- 카테고리별로 색인을 따로 두면 찾는 범위를 좁힐 수 있다.
--
-- **분류는 트리인데 색인은 카테고리 단위다.** 분류는 사람이 보기 좋으라고 있는
-- 것이고, 검색은 카테고리 전체에서 한다 — 사람이 어느 서랍에 넣었는지 기억해야
-- 찾을 수 있다면 검색이 아니다.
--
-- ── 파일 실물은 DB 에 넣지 않는다 ───────────────────────────
--
-- 운영시스템 디스크에 두고(`Rag:UploadRoot`) 여기에는 경로만 적는다. 문서는
-- 수십 MB 가 되기도 하고, DB 에 넣으면 백업·복제가 그만큼 무거워진다.
-- **LLM 서버는 파일을 갖지 않는다** — 운영시스템이 읽어 글자로 바꾼 뒤
-- 임베딩만 LLM 서버에 맡긴다(/embed).
--
-- ── 같은 파일을 두 번 올리는 일 ─────────────────────────────
--
-- sha256 을 적어 둔다. 막지는 않는다 — 분류를 옮기려고 다시 올리는 일이
-- 흔하고, 같은 내용이 두 서랍에 있어야 하는 경우도 있다. 다만 **색인할 때
-- 같은 해시는 한 번만 넣는다**(RagLibrary 가 거른다).
-- ============================================================

CREATE TABLE IF NOT EXISTS scom.rag_categories (
    id           text         NOT NULL,
    name         text         NOT NULL,
    description  text,
    status       integer      NOT NULL DEFAULT 1,
    indexed_at   timestamptz,
    chunk_count  integer      NOT NULL DEFAULT 0,
    doc_count    integer      NOT NULL DEFAULT 0,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    created_by   text,
    updated_at   timestamptz,
    updated_by   text,
    is_deleted   boolean      NOT NULL DEFAULT false,
    CONSTRAINT pk_rag_categories PRIMARY KEY (id)
);

COMMENT ON TABLE  scom.rag_categories            IS 'RAG 단위. 색인 파일 하나에 대응한다';
COMMENT ON COLUMN scom.rag_categories.id         IS '사람이 읽는 열쇠 (영문·숫자·하이픈)';
COMMENT ON COLUMN scom.rag_categories.indexed_at IS '마지막으로 색인을 만든 때';
COMMENT ON COLUMN scom.rag_categories.chunk_count IS '색인에 든 토막 수';

CREATE TABLE IF NOT EXISTS scom.rag_folders (
    id           bigint       GENERATED BY DEFAULT AS IDENTITY,
    category_id  text         NOT NULL,
    parent_id    bigint,
    name         text         NOT NULL,
    sort_no      integer      NOT NULL DEFAULT 0,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    created_by   text,
    updated_at   timestamptz,
    updated_by   text,
    is_deleted   boolean      NOT NULL DEFAULT false,
    CONSTRAINT pk_rag_folders PRIMARY KEY (id),
    CONSTRAINT fk_rag_folders_category FOREIGN KEY (category_id)
        REFERENCES scom.rag_categories (id) ON DELETE CASCADE,
    CONSTRAINT fk_rag_folders_parent FOREIGN KEY (parent_id)
        REFERENCES scom.rag_folders (id) ON DELETE CASCADE
);

COMMENT ON TABLE  scom.rag_folders           IS '분류. 카테고리 안의 트리다';
COMMENT ON COLUMN scom.rag_folders.parent_id IS 'null 이면 카테고리 바로 아래';

CREATE INDEX IF NOT EXISTS ix_rag_folders_category ON scom.rag_folders (category_id, parent_id);

CREATE TABLE IF NOT EXISTS scom.rag_documents (
    id            bigint       GENERATED BY DEFAULT AS IDENTITY,
    category_id   text         NOT NULL,
    folder_id     bigint,
    file_name     text         NOT NULL,
    content_type  text,
    size_bytes    bigint       NOT NULL DEFAULT 0,
    sha256        text,
    stored_path   text         NOT NULL,
    status        text         NOT NULL DEFAULT 'pending',
    chunk_count   integer      NOT NULL DEFAULT 0,
    error         text,
    indexed_at    timestamptz,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    created_by    text,
    is_deleted    boolean      NOT NULL DEFAULT false,
    CONSTRAINT pk_rag_documents PRIMARY KEY (id),
    CONSTRAINT fk_rag_documents_category FOREIGN KEY (category_id)
        REFERENCES scom.rag_categories (id) ON DELETE CASCADE,
    CONSTRAINT fk_rag_documents_folder FOREIGN KEY (folder_id)
        REFERENCES scom.rag_folders (id) ON DELETE SET NULL
);

COMMENT ON TABLE  scom.rag_documents             IS 'RAG 가 읽는 문서. 실물은 디스크에 있다';
COMMENT ON COLUMN scom.rag_documents.folder_id   IS 'null 이면 분류 미지정(카테고리 바로 아래)';
COMMENT ON COLUMN scom.rag_documents.stored_path IS 'Rag:UploadRoot 기준 상대 경로';
COMMENT ON COLUMN scom.rag_documents.status      IS 'pending | indexed | failed | skipped';
COMMENT ON COLUMN scom.rag_documents.sha256      IS '같은 내용을 색인에 두 번 넣지 않으려고 적어 둔다';

CREATE INDEX IF NOT EXISTS ix_rag_documents_category ON scom.rag_documents (category_id, folder_id);
CREATE INDEX IF NOT EXISTS ix_rag_documents_status   ON scom.rag_documents (category_id, status);

