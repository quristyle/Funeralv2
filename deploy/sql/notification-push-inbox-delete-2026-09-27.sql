-- ============================================================
-- 알림함에서 지우기 — scom.push_send_logs 에 칸 하나
-- ============================================================
--
-- 「내 알림함」의 카드를 **왼쪽으로 밀면 지운다**(오른쪽은 읽음 처리다).
-- 읽음만으로는 안 되는 자리가 있다 — 읽을 것도 없이 치우려는 알림이
-- 그렇다. 읽음으로 찍으면 목록에서는 빠지지만 그것은 「봤다」는 뜻이라
-- 나중에 「안 읽은 것만」을 풀어 보면 다시 나온다.
--
-- ── 줄을 지우지 않는다 ───────────────────────────────────────
--
-- 이 표는 **받는 사람의 알림함이자 보낸 쪽의 발송 기록**이다. 한 줄을
-- 진짜로 지우면 「푸시 현황」·「발송 이력」의 건수가 함께 줄어든다 —
-- 받는 사람이 제 알림함을 정리한 것뿐인데 **보낸 통계가 바뀐다.**
-- 실패 사유를 모아 보는 화면(FailureReason)도 마찬가지로, 못 간 알림을
-- 받는 쪽이 치우면 그 실패가 집계에서 사라진다.
--
-- 그래서 「알림함에서만 감춘다」로 둔다. 거르는 곳은 알림함 세 길뿐이다
-- (/inbox · /inbox/unread-count · /inbox/read-all). 발송 화면은 안 거른다.
--
-- ── 묶음 단위로 찍는다 ───────────────────────────────────────
--
-- 줄은 기기 단위이고 알림함은 사람 단위다(batch_id). 읽음이 그렇듯
-- 지움도 그 묶음에 딸린 그 사람의 줄을 **전부** 찍는다 — 한 줄만 찍으면
-- 기기 둘을 쓰는 사람의 목록에 나머지 한 줄이 그대로 남는다.
--
-- ── 남의 것을 못 지운다 ──────────────────────────────────────
--
-- 열쇠만 보고 갱신하지 않는다. owner_type='jsini' 와 owner_key 를 함께
-- 본다(읽음 처리와 같은 규칙이다).
--
-- 멱등하다. 되돌리려면 맨 아래.
-- **운영 반영 완료** (2026-09-27 — 개발과 운영이 같은 DB 를 본다).

BEGIN;

ALTER TABLE scom.push_send_logs
    ADD COLUMN IF NOT EXISTS deleted_at timestamp with time zone;

COMMENT ON COLUMN scom.push_send_logs.deleted_at
    IS '받는 사람이 제 알림함에서 치운 때(UTC). NULL 이면 알림함에 남아 있다. 발송 기록으로서의 줄은 그대로다 — 푸시 현황·발송 이력은 이 값을 거르지 않는다.';

COMMIT;

