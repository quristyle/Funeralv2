--
-- ── 무엇을 적는 표인가 ──────────────────────────────────────
--
-- **권한 밖의 화면을 누가 어떤 주소로 열려 했나.** 포털은 한 회로 안에서
-- 라우팅만 바뀌어 주소를 쳐서 들어와도 HTTP 요청이 한 건도 안 나간다 —
-- nginx 접근 로그에는 로그인 한 번과 WebSocket 하나뿐이다. 막혔다는 사실을
-- 아는 자리가 라우터 앞의 문 하나뿐이고, 그래서 거기서 한 줄씩 적어 보낸다.
--
-- scom.menu_usage_logs 와 **짝이다.** 저쪽은 열린 화면을, 이쪽은 막힌 화면을
-- 적는다. 한 표로 섞지 않는 까닭은 엔티티(BlockedAccessLog) 머리말에 있다.
--
-- ── reason 둘을 가르는 것이 요점이다 ────────────────────────
--
--   NO_PERMISSION  메뉴는 찾았는데 그 사람에게 열람 권한이 없다.
--                  → 메뉴 권한 화면(/admin/auth/menu-role)에서 체크 하나.
--   UNMANAGED      가리킬 메뉴가 없다 — 권한관리 범위 밖의 화면이다.
--                  → 메뉴로 등록하거나, 화면이 [ScreenAccess] 로 부모를
--                    가리켜야 한다. **권한을 아무리 줘도 안 열린다.**
--
-- ── 외래키를 걸지 않는다 ────────────────────────────────────
--
-- 메뉴를 지우면 그 화면에서 막힌 기록까지 함께 사라지는데, 지난 일을 적어 둔
-- 표에서 그것은 자료 손실이다. 계정도 마찬가지다 — 지운 사람의 줄도 남는다.
-- menu_usage_logs 와 같은 판단이다.
--
-- ── 한 해만 들고 있다 ───────────────────────────────────────
--
-- 적는 길에 하루 한 번 청소가 얹혀 있다(BlockedAccessService.RetentionDays).
-- menu_usage_logs 와 **같은 값**이어야 한다 — 나란히 놓고 보는 표라 보관
-- 기간이 다르면 어느 날부터 한쪽만 남아 대조가 조용히 깨진다.
-- ============================================================

START TRANSACTION;
CREATE TABLE scom.blocked_access_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    occurred_at timestamp with time zone NOT NULL,
    user_id character varying(128) NOT NULL,
    href character varying(512) NOT NULL,
    route_key character varying(128),
    screen_type character varying(256),
    menu_path character varying(512),
    reason character varying(32) NOT NULL,
    from_path character varying(512),
    client_ip character varying(64),
    CONSTRAINT "PK_blocked_access_logs" PRIMARY KEY (id)
);
COMMENT ON TABLE scom.blocked_access_logs IS '차단 한 건 — 권한 밖의 화면을 누가 어떤 주소로 열려 했나.';
COMMENT ON COLUMN scom.blocked_access_logs.id IS '줄 번호';
COMMENT ON COLUMN scom.blocked_access_logs.occurred_at IS '막힌 때 (UTC)';
COMMENT ON COLUMN scom.blocked_access_logs.user_id IS '막힌 사람의 로그인 아이디 (scom.accounts.user_id)';
COMMENT ON COLUMN scom.blocked_access_logs.href IS '막힌 주소. 사람이 실제로 연 그 값이라 매개변수가 들어 있다
            (/admin/system/account/jupark/app) — 「누구의 것을 보려 했나」가
            이 칸에만 남는다.';
COMMENT ON COLUMN scom.blocked_access_logs.route_key IS '화면이 선언한 열쇠. 신고가 없는 화면은 비어 있다';
COMMENT ON COLUMN scom.blocked_access_logs.screen_type IS '라우터가 끼우려던 화면 클래스. 「어느 파일이냐」의 답이다';
COMMENT ON COLUMN scom.blocked_access_logs.menu_path IS '권한을 따진 메뉴 경로. 메뉴를 못 찾았으면 비어 있다';
COMMENT ON COLUMN scom.blocked_access_logs.reason IS '왜 막혔나 — NO_PERMISSION(권한 없음) · UNMANAGED(관리 밖).
            둘을 가르는 것이 이 표의 요점이다: 앞엣것은 권한 화면에서 체크
            하나면 끝나고, 뒤엣것은 메뉴를 만들거나 코드를 고치기 전에는 안 열린다.';
COMMENT ON COLUMN scom.blocked_access_logs.from_path IS '직전에 보던 화면. 「어디서 눌러 들어왔나」다';
COMMENT ON COLUMN scom.blocked_access_logs.client_ip IS '접속 주소. 위조할 수 있는 값이라 보여 주기 전용이다 —
            이것으로 무엇을 판단하지 않는다(ClientAddress 머리말).';

CREATE INDEX "IX_blocked_access_logs_occurred_at" ON scom.blocked_access_logs (occurred_at);

CREATE INDEX "IX_blocked_access_logs_route_key" ON scom.blocked_access_logs (route_key);

CREATE INDEX "IX_blocked_access_logs_user_id_occurred_at" ON scom.blocked_access_logs (user_id, occurred_at);

