CREATE TABLE IF NOT EXISTS projmng.ai_usage_history (
    history_key     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    runner_nm       varchar(100)  NOT NULL,
    runner_kind     varchar(20)   NOT NULL,
    bucket_nm       varchar(60)   NOT NULL DEFAULT '',
    ok              boolean       NOT NULL DEFAULT true,
    session_pct     numeric(5,2),
    session_reset_at timestamp,
    week_pct        numeric(5,2),
    week_reset_at   timestamp,
    week_opus_pct   numeric(5,2),
    week_opus_reset_at timestamp,
    month_pct       numeric(5,2),
    month_reset_at  timestamp,
    limit_tokens    bigint,
    remaining_tokens bigint,
    plan_nm         varchar(50),
    observed_at     timestamp with time zone NOT NULL DEFAULT now(),
    cre_dt          timestamp with time zone DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_ai_usage_history_observed
    ON projmng.ai_usage_history (observed_at DESC);

CREATE INDEX IF NOT EXISTS ix_ai_usage_history_kind
    ON projmng.ai_usage_history (runner_kind, bucket_nm, observed_at DESC);

COMMENT ON TABLE projmng.ai_usage_history IS
    'AI 모델 사용량(주간 사용량비율 등) 주기별 수집 이력. 시간별·일별·월별 추이 분석용.';

