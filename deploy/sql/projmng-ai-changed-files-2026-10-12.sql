-- AI 작업 실행이 건드린 파일 목록 — projmng.ai_task_run.changed_files (2026-10-12)
-- ============================================================
--
-- 「빠른 지시」 상세의 **처리 요약** 아래에 **처리 파일** 묶음을 세우기 위한 칸이다.
--
-- [왜 diff_stat 으로는 안 되나]
--
-- 그 칸(varchar(500))에는 `git diff --stat` 의 글자가 그대로 들어간다. 그런데
-- `--stat` 은 긴 경로를 `.../Components/Pages/X.razor` 로 **줄여서** 내고,
-- 그 결과가 다시 480자에서 잘려 **꼬리의 파일들과 합계 줄이 통째로 사라진다**
-- (run 504 가 `web/src/Apps/JSi` 에서 끊겨 있다). 한국어 파일명은 8진 탈출
-- (`"\355\225\234…"`)로 적혀 읽을 수도 없다. 숫자를 보여 주는 데는 쓸 만해도
-- **파일 목록으로는 못 쓴다.**
--
-- 그래서 실행기가 `--name-status` 로 따로 물어 여기에 적는다. 한 줄에 파일 하나이고
-- 모양은 `상태<탭>경로` 다 — `A` 추가 · `M` 수정 · `D` 삭제 · `R` 이름변경 ·
-- `…` 은 「외 N개」를 적은 마지막 줄이다. **추적 안 하던 새 파일도 `A` 로 들어간다**
-- (`git ls-files --others`) — 커밋 전이면 `git diff` 에는 한 줄도 안 나오기 때문이다.
--
-- diff_stat 은 그대로 둔다. 「몇 줄이 바뀌었나」는 거기에만 있고, 이 칸이
-- 생기기 전의 건은 그것으로만 그릴 수 있다(화면이 되읽어 쓴다).
--
-- 실행:
--   psql -h 127.0.0.1 -p 31015 -U projmng -d projmng -f deploy/sql/projmng-ai-changed-files-2026-10-12.sql
--

ALTER TABLE projmng.ai_task_run
    ADD COLUMN IF NOT EXISTS changed_files text;

COMMENT ON COLUMN projmng.ai_task_run.changed_files IS
    '이 실행이 건드린 파일 목록. 한 줄에 「상태<탭>경로」(A 추가 · M 수정 · D 삭제 · R 이름변경 · … 외 N개). 화면의 「처리 파일」이 읽는다.';
