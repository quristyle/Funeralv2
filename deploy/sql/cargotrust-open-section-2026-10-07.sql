-- ============================================================
-- 개방식 영업소를 표시한다 (cargotrust DB · 2026-10-07)
-- ============================================================
--
-- 영업소 477건이 전부 폐쇄식으로 들어와 있었다. 받아 온 API
-- (data.ex.co.kr `basicinfo/updownIcList`)가 **구간 유형을 주지 않아서**,
-- 모를 때의 안전한 쪽(폐쇄식)으로 둔 것이다 — 개방식으로 잘못 두면 아닌
-- 구간에 일괄 50% 가 붙지만, 폐쇄식이면 비율대로 세므로 틀려도 할인이
-- 과하게 나오지 않는다.
--
-- 고속도로 공공데이터 포털의 **영업소 파일데이터**(ETC/75, 2026-10-05 자)에
-- 그 칸이 있다. 942줄 중 우리 표와 겹치는 477건을 대조해 아래 25곳을 골랐다.
--
-- [칸 이름을 조심한다 — 「영업방식」이 아니라 「영업형태」다]
--
-- 파일에 비슷한 칸이 둘이다. 처음에 `영업방식구분코드`(0·1·2·3)를 썼는데
-- 그것으로는 **경부선 서울과 「서영암(개)」가 같은 값**이 나왔다 — 뒤엣것은
-- 이름이 대놓고 개방식이다. 맞는 칸은 `영업형태구분코드`(0 폐쇄식 · 1 개방식)다.
--
-- [다섯 갈래로 맞춰 보고 넣었다]
--
--   * 노선 100(수도권제1순환) 본선요금소가 통째로 1 — 서울외곽순환은 개방식이다
--   * 노선 120(경인선) 인천, 110(제2경인) 남인천/안양과천도 1
--   * 이름에 「(개)」가 붙은 4곳이 모두 1 에 들어 있다
--   * 경부선(001)에서 1 인 것은 대왕판교/판교 둘뿐 — 실제 개방식 본선요금소다
--   * 경부선 서울/동수원/대전은 0 — 통행권을 뽑는 폐쇄식이 맞다
--
-- 멱등하다. 되돌리기는 맨 아래.

SET search_path TO cargotrust;

BEGIN;

WITH open_units (unit_code) AS (VALUES
    ('029'),  -- 가락(개) (노선 104)
    ('003'),  -- 강동고덕 (노선 029)
    ('062'),  -- 구리남양주 (노선 100)
    ('068'),  -- 김포 (노선 100)
    ('053'),  -- 남인천 (노선 110)
    ('092'),  -- 내서 (노선 010)
    ('057'),  -- 다사 (노선 700)
    ('091'),  -- 대동(개) (노선 055)
    ('069'),  -- 대왕판교 (노선 001)
    ('074'),  -- 덕소삼패 (노선 060)
    ('025'),  -- 동부산 (노선 066)
    ('012'),  -- 서영암(개) (노선 010)
    ('061'),  -- 성남 (노선 100)
    ('013'),  -- 순천만 (노선 010)
    ('067'),  -- 시흥 (노선 100)
    ('011'),  -- 인천 (노선 120)
    ('056'),  -- 일로 (노선 015)
    ('058'),  -- 지천 (노선 700)
    ('064'),  -- 청계 (노선 100)
    ('073'),  -- 초이(개) (노선 029)
    ('063'),  -- 토평 (노선 100)
    ('065'),  -- 판교 (노선 001)
    ('066'),  -- 하남 (노선 035)
    ('059'),  -- 하남감북3 (노선 029)
    ('002')   -- 하남감북4 (노선 029)
)
UPDATE toll_plaza p
   SET section_type = 'OPEN',
       updated_at   = NOW()
  FROM open_units o
 WHERE p.unit_code = o.unit_code
   AND p.section_type <> 'OPEN';

COMMIT;

