  notified_at          timestamptz,
  created_by           text NOT NULL DEFAULT '',
  created_at           timestamptz NOT NULL DEFAULT now(),
  modified_by          text,
  modified_at          timestamptz,
  action_service       text,
  menu_context         text,
  remote_addr          text,
  remote_machine_info  text,
  is_deleted           boolean NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS ix_weather_location_warnings_weather_warning_id
  ON ghub.weather_location_warnings (weather_warning_id);
CREATE INDEX IF NOT EXISTS ix_weather_location_warnings_weather_location_id
  ON ghub.weather_location_warnings (weather_location_id);

