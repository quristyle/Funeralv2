/// <summary>
/// 행정구역 이름 → 기상청 중기예보 구역코드(육상 · 기온). 중기예보는 격자로 못 묻고 구역코드로만 물으며,
/// 내 위치는 좌표에서 찾은 시·도·시·군으로 코드를 고른다. 육상 코드는 기온 코드 앞자리로 가른다.
/// 코드는 기상청에 실제로 확인한 값이다 — 틀린 코드는 오류가 아니라 빈 응답이 된다.
/// </summary>
public static class MidTermRegions
{
    /// <summary>좌표에서 찾은 시·도·시·군으로 (육상, 기온) 구역코드를 고른다. 시·도조차 모르면 (null, null) — 주간 예보를 만들지 않는다.</summary>
    public static (string? Land, string? Temp) Resolve(string? region1, string? region2)
    {
        var temp = TempCode(region1, region2);
        return temp is null ? (null, null) : (LandCodeOf(temp), temp);
    }

    /// <summary>
    /// 중기 <b>기온</b> 구역코드. 시·군·구 → 없으면 시·도 대표 도시.
    /// </summary>
    private static string? TempCode(string? region1, string? region2)
    {
        var sido = Trim(region1);
        if (sido is null) return null;

        var city = BaseCity(Trim(region2));

        // **시·도를 함께 본다.** 「고성」이 강원과 경남에 하나씩, 「광주」가
        // 경기와 광주광역시에 하나씩, 「동구」·「중구」는 광역시마다 있다.
        if (city is not null && Cities.TryGetValue((sido, city), out var found))
        {
            return found;
        }

        // 광역시의 구는 표에 없다 — 「부산 해운대구」의 중기예보는 「부산」이다.
        // 도(道)에서도 못 찾으면 대표 도시로 간다(읍·면·동만 있고 시·군이 빈 행).
        return Defaults.GetValueOrDefault(sido);
    }

    /// <summary>기온 코드 앞자리로 육상 구역을 가른다. 울릉도·독도는 육상 구역이 없어 경상북도로 묶는다.</summary>
    private static string LandCodeOf(string temp) => temp[..4] switch
    {
        "11C1" => "11C10000",   // 충청북도
        "11C2" => "11C20000",   // 대전 · 세종 · 충청남도
        "11D1" => "11D10000",   // 강원도 영서
        "11D2" => "11D20000",   // 강원도 영동
        "11E0" => "11H10000",   // 울릉도 · 독도 → 경상북도
        "11F1" or "21F1" => "11F10000",   // 전북자치도
        "11F2" or "21F2" => "11F20000",   // 광주 · 전라남도
        "11G0" => "11G00000",   // 제주도
        "11H1" => "11H10000",   // 대구 · 경상북도
        "11H2" => "11H20000",   // 부산 · 울산 · 경상남도
        _ => "11B00000",        // 서울 · 인천 · 경기도 (11A · 11B)
    };

    /// <summary>
    /// 시·군·구 이름에서 중기예보 시 이름을 뽑는다(창원시성산구 → 창원). 구를 먼저 떼야 한다 — 「시흥시」처럼 이름에 「시」가 든 곳이 어긋나지 않는다.
    /// </summary>
    private static string? BaseCity(string? region2)
    {
        if (region2 is null) return null;

        // 끝의 시·군·구 한 글자를 먼저 뗀다.
        var trimmed = region2.Length > 1 && region2[^1] is '시' or '군' or '구'
            ? region2[..^1]
            : region2;

        // 남은 것에 「시」가 있으면 그 앞이 시 이름이다(고양시덕양 → 고양).
        var si = trimmed.IndexOf('시');
        return si > 0 ? trimmed[..si] : trimmed;
    }

    private static string? Trim(string? value)
        => string.IsNullOrWhiteSpace(value) ? null : value.Trim();

