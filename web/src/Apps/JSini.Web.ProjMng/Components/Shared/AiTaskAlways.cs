namespace JSini.Web.ProjMng.Components.Shared;

/// <summary>
/// 지시마다 <b>무조건</b> 뒤에 붙는 문구. 「빠른 지시」로 새로 보내는 건과
/// 「이어서 지시」가 같은 것을 쓴다.
/// </summary>
/// <remarks>
/// <para>
/// <b>사람이 매번 적지 않아도 되는 것만 둔다.</b> 여기 적힌 것들은 지시마다
/// 달라지지 않는데 빠뜨리면 그 회차가 통째로 헛도는 것들이다 —
/// 고쳤다고 말만 하고 파일은 안 건드린 채 끝나거나, 다 고쳐 놓고
/// 워크트리에만 남겨 둬 다음 회차가 같은 일을 다시 한다.
/// </para>
/// <para>
/// [왜 한곳에 모았나]
/// </para>
/// <para>
/// 한동안 이 문구는 <c>AiTaskActions</c> 안의 private const 였고,
/// <b>「이어서 지시」에만 붙었다.</b> 그래서 같은 사람이 같은 자리에 던진
/// 두 건이 서로 다른 지시를 받았다 — 처음 보낸 건은 커밋·push 를 말해 주지
/// 않아 고친 것이 워크트리에만 남고, 이어서 지시한 건만 올라갔다.
/// 문구를 복사해 두면 한쪽만 고쳐져 그 어긋남이 다시 생기므로 여기 하나만 둔다.
/// </para>
/// <para>
/// [커밋·push 줄이 왜 있나]
/// </para>
/// <para>
/// 실행기는 AI 가 커밋을 안 했어도 게이트에서 한 번 더 커밋한다
/// (<c>PushGate</c>). 그래도 <b>지시에 박아 두는 편이 낫다</b> — 게이트가
/// 집어 가는 것은 「바뀐 파일」뿐이라, AI 가 브랜치를 따로 파거나 워크트리를
/// 옮겨 앉으면 그 자리의 변경은 게이트 눈에 안 보인다. 지시가 먼저 말해 주면
/// 그런 갈림이 애초에 안 생긴다.
/// </para>
/// <para>
/// <b>올리기를 끈 건에도 붙는다.</b> 실제로 <c>main</c> 까지 가는지는 화면의
/// 올리기 칸(<c>ai_task.auto_push</c>)과 게이트가 정하지, 지시 문구가 정하지
/// 않는다 — 끈 건은 커밋만 남고 거기서 멈춘다.
/// </para>
/// <para>
/// [main 까지 확인시키는 줄이 왜 있나]
/// </para>
/// <para>
/// 커밋·push 를 말해 주는 것만으로는 모자랐다. AI 는 <b>제 작업 가지에
/// 커밋하고 그 가지를 밀고 나서 「push 했다」고 끝낸다.</b> 그 가지는
/// <c>main</c> 이 아니므로 배포도 안 나가고, 다음 회차가 같은 자리를 다시
/// 들출 때에야 드러난다.
/// </para>
/// <para>
/// 실제로 그렇다 — 올리기를 켠 채 <c>succeeded</c> 로 끝난 지시 114건 가운데
/// <b>28건(넷에 하나)이 <c>pushed_commit</c> 이 비어 있다</b>(2026-09-24 조회).
/// 그래서 「올렸다」로 끝내지 말고 <b>`origin/main` 에 들어갔는지 눈으로
/// 확인하고, 못 올렸으면 무엇이 막았는지 적으라</b>를 지시에 박아 둔다.
/// 막힌 이유(게이트·충돌·금지 경로)가 결과에 남아야 사람이 이어받는다.
/// </para>
/// <para>
/// [DB 줄이 왜 있나]
/// </para>
/// <para>
/// 작업 환경에는 운영 서버 SSH 가 없어서 스키마를 바꿔야 하는 지시가 오면
/// 「SQL 파일은 만들어 뒀으니 사람이 돌려 달라」로 끝나기 쉽다. 그런데 접속
/// 정보는 소스에 있고 실제로 닿는다 — 그것을 모르는 채로 넘기면 코드만
/// 올라가고 표는 안 바뀐 상태로 배포가 나간다. 그래서 「찾아서 직접 하라」를
/// 지시에 박아 둔다.
/// </para>
/// <para>
/// [셸 줄이 왜 있나]
/// </para>
/// <para>
/// 2026-10-10, 지시 292 가 <c>grep -A 5 "class AccountDto" $(find ./web/src
/// -name "AccountDto.cs")</c> 를 돌렸다. <c>find</c> 가 아무것도 못 찾아
/// 치환이 빈 문자열로 펴졌고, <b>파일 인자를 잃은 <c>grep</c> 은 표준입력을
/// 읽으러 갔다.</b> CLI 가 붙여 둔 pty 에는 EOF 가 영영 안 와서 그 명령이
/// 그대로 멈춰 섰다 — 출력 0 바이트, 48분.
/// </para>
/// <para>
/// <b>일은 그때 이미 다 끝나 있었다.</b> 커밋도 push 도 <c>origin/main</c>
/// 까지 들어갔다. 그런데 Antigravity CLI 는 print 모드에서 <b>배경 작업이
/// 다 끝나야</b> 빠져나온다 — <c>root agent idle; waiting up to 2h0m0s for 1
/// background task(s)</c>. 셸 명령이 2초 안에 안 끝나면 CLI 가 그것을 배경
/// 작업으로 알아서 돌리므로(<c>WaitMsBeforeAsync</c>), 멈춘 명령 하나가 곧
/// 안 끝나는 회차가 된다. 그래서 <b>다 된 건이 <c>--print-timeout 120m</c>
/// 을 꽉 채우고 잘린 뒤 '실패'로 앉는다</b> — 그동안 실행기 슬롯
/// (<c>MaxParallel</c>) 하나도 같이 물고 있다.
/// </para>
/// <para>
/// 그래서 두 마디를 함께 둔다. 앞은 <b>그 꼴을 안 만드는</b> 쪽이고, 뒤는
/// <b>그래도 생겼을 때 빠져나오는</b> 쪽이다 — 292 의 에이전트는 멈춘 작업을
/// 세 번이나 들여다보고도(<c>Check task</c>) 멈출 수 있다는 것을 몰라
/// 그대로 끝냈다.
/// </para>
/// </remarks>
internal static class AiTaskAlways
{
    /// <summary>늘 따라붙는 문구 그 자체.</summary>
    public const string Text =
        "작업에 생성되는 파일이나 변경된 내용이 실제 작성되었는지 다시 확인하고, "
        + "모든 작업이 끝나면 반드시 main 브랜치에 commit과 push를 수행해라.\n\n"
        + "작업하던 가지에 커밋만 해 두고 끝내지 마라. 고친 것이 origin/main 에 "
        + "들어갔는지 git log origin/main 으로 직접 확인하고, 올리지 못했으면 "
        + "무엇이 막았는지 결과에 적어라.\n\n"
        + "DB 작업이 필요하면 DB 연결정보를 소스에서 확인하여 사용하여 직접 처리하고, "
        + "반영한 결과까지 조회해서 확인해라.\n\n"
        + "셸 명령은 입력을 기다리는 꼴로 적지 마라. `$(find ...)` 처럼 치환으로 만든 "
        + "파일 목록을 grep·cat 에 바로 넘기면, 찾은 것이 없을 때 인자가 통째로 사라져 "
        + "그 명령이 표준입력을 기다리며 안 끝난다. 파일을 뒤질 때는 `grep -r 무늬 경로` 나 "
        + "`find ... -exec grep ... {} +` 를 쓰고, 끝내기 전에 남은 배경 작업이 있는지 "
        + "보고 있으면 멈춰라.";

    /// <summary>
    /// 사람이 적은 말 뒤에 <see cref="Text"/> 를 붙인다.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>빈 글에는 붙이지 않는다.</b> 「이어서 지시」는 덧붙일 말 없이 보낼 수
    /// 있는데, 거기에 이것만 실어 보내면 <b>사람이 아무 말도 안 했는데 지시가
    /// 하나 생긴다.</b>
    /// </para>
    /// <para>
    /// <b>이미 들어 있으면 또 붙이지 않는다.</b> 다시 보내기·이어서 지시로
    /// 같은 글이 몇 번 돌 수 있고, 그때마다 붙으면 지시 끝이 같은 문단으로
    /// 도배된다.
    /// </para>
    /// </remarks>
    /// <param name="written">사람이 적은 말.</param>
    /// <returns>문구가 붙은 지시. 적은 말이 비어 있으면 받은 것을 그대로.</returns>
    public static string? Append(string? written)
    {
        if (string.IsNullOrWhiteSpace(written))
        {
            return written;
        }

        return written.Contains(Text, StringComparison.Ordinal)
            ? written
            : written.TrimEnd() + "\n\n" + Text;
    }
}
